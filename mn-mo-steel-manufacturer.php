                        <p>For these components, the steel needs more than basic tensile strength. It also needs sufficient toughness and hardenability for the relevant section size.</p>
                        <p class="mb-0">Mn-Mo steels can be a useful choice where these requirements fall beyond the practical performance range of simpler carbon steels.</p>
