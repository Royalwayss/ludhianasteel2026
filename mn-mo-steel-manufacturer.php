                        </div>
                        <hr class="system-line">
                        <p>35Mn6Mo3 is a manganese-molybdenum engineering grade associated with EN16-type specifications. A typical composition is in the region of:</p>
                        <ul>
                            <li><i class="bi bi-arrow-right-square-fill infra-li-icon"></i>Carbon: 0.32&ndash;0.40%</li>
                            <li><i class="bi bi-arrow-right-square-fill infra-li-icon"></i>Manganese: 1.30&ndash;1.80%</li>
                            <li><i class="bi bi-arrow-right-square-fill infra-li-icon"></i>Silicon: 0.10&ndash;0.35%</li>
                            <li><i class="bi bi-arrow-right-square-fill infra-li-icon"></i>Molybdenum: 0.20&ndash;0.35%</li>
                        </ul>
                        <p>These values are useful for understanding the alloy system, but the governing customer standard should always control the final chemistry.</p>
                        <p class="mb-0">The comparatively high manganese content, together with molybdenum, gives the grade its characteristic heat-treatment response and engineering strength.</p>
                    </div>
