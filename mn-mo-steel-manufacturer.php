                <!-- Mn-Mo Steel vs Cr-Mo Steel -->
                <div class="col-lg-6 col-md-12">
                    <div class="prdo-system-card h-100">
                        <div class="prdo-system-card-top">
                            <div class="prdo-system-icon"><i class="bi bi-sliders"></i></div>
                            <h4>Mn-Mo Steel vs Cr-Mo Steel</h4>
                        </div>
                        <hr class="system-line">
                        <p>Mn-Mo and Cr-Mo steels are both alloy engineering families, but they use different principal alloy systems.</p>
                        <p><strong>Mn-Mo Steel:</strong> Grades such as EN16 / 35Mn6Mo3 rely primarily on manganese and molybdenum to provide strength and hardenability.</p>
                        <p><strong>Cr-Mo Steel:</strong> Grades such as EN19 / SAE4140 / 42CrMo4 use chromium and molybdenum and are generally associated with a different hardenability and mechanical-performance range.</p>
                        <p class="mb-0">The correct family should therefore be selected from the actual component requirements rather than assuming one is simply a substitute for the other.</p>
                    </div>
                </div>
