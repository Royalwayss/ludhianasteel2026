                </h2>
            </div>
            <div class="prdo-glass-panel">
                <p>Alloy steels are steels in which elements such as chromium, nickel, molybdenum, manganese or vanadium are used to achieve specific metallurgical properties.</p>
                <p>Depending on the grade and alloying system, these additions can improve characteristics such as hardenability, toughness, fatigue resistance, wear resistance and response to heat treatment. Chromium, for example, contributes to hardenability and carbide formation; nickel can improve toughness; molybdenum can improve high-temperature strength and hardenability; and vanadium contributes to grain refinement and wear-resistant carbide formation.</p>
                <p class="mb-0">That makes alloy steel particularly relevant where an ordinary carbon steel may not provide the combination of strength, hardness or toughness required by the final component.</p>
