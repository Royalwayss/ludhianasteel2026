                </h2>
            </div>
            <div class="prdo-glass-panel">
                <p>Carbon content has a significant influence on how steel behaves during manufacturing and in service.</p>

                <h4 class="text-white mt-4 mb-2">Low-Carbon Steel</h4>
                <p>Grades such as C15, SAE1008, SAE1010, SAE1018 and SAE1020 sit toward the lower-carbon end of the range. These steels are generally selected where properties such as formability, ductility, weldability, cold working and straightforward machining are important to the manufacturing process. They are commonly considered for formed parts, fasteners and general engineering components depending on the specification.</p>

                <h4 class="text-white mt-4 mb-2">Medium-Carbon Steel</h4>
                <p>Grades such as C35, C40, C45, EN8, SAE1040 and SAE1045 offer greater strength and hardness potential. They are frequently associated with components such as shafts, axles, pins, gears, studs, machine parts and forged engineering components. Their response to heat treatment also makes them useful where the component requires a controlled balance of strength and toughness.</p>

                <h4 class="text-white mt-4 mb-2">Higher-Carbon Grades</h4>
                <p class="mb-0">Grades such as Ck60, C50, SAE1050 and EN9 move further toward hardness and wear-related performance. These steels need more careful consideration of machining, forming and heat treatment because increasing carbon content generally reduces ductility while increasing achievable hardness.</p>
            </div>
        </div>
    </section>





